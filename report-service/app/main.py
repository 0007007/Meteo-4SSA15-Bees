"""report-service: 7th microservice of the Meteo App, written in Python with FastAPI.

Run:  python -m app.main          (or: uvicorn app.main:app --port 8087 --reload)
Docs: http://localhost:8087/docs  (Swagger UI generated by FastAPI)
"""
import logging
import os
from contextlib import asynccontextmanager

import py_eureka_client.eureka_client as eureka_client
from fastapi import FastAPI

from app.config import settings
from app.database import Base, engine, ensure_database_exists
from app.exceptions import register_exception_handlers
from app.routers import report_router, schedule_router

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s - %(message)s")
log = logging.getLogger("report-service")


async def register_in_eureka() -> bool:
    """Registers this Python service in Eureka so the gateway can route lb://report-service to it."""
    base_url = f"http://{settings.instance_host}:{settings.port}"
    options = dict(
        eureka_server=settings.eureka_url,
        app_name=settings.app_name,
        instance_host=settings.instance_host,
        instance_ip=settings.instance_ip,
        instance_port=settings.port,
    )
    try:
        try:
            await eureka_client.init_async(**options, health_check_url=f"{base_url}/health",
                                           status_page_url=f"{base_url}/health", home_page_url=base_url)
        except TypeError:  # older/newer client without these keyword arguments
            await eureka_client.init_async(**options)
        log.info("Registered in Eureka as %s", settings.app_name)
        return True
    except Exception as exc:  # the API still works without Eureka (call it on :8087)
        log.warning("Eureka registration failed (%s); is discovery-server running on %s?", exc, settings.eureka_url)
        return False


@asynccontextmanager
async def lifespan(app: FastAPI):
    ensure_database_exists()
    Base.metadata.create_all(bind=engine)  # creates the 2 tables if missing (like ddl-auto: update)
    os.makedirs(settings.reports_dir, exist_ok=True)
    registered = await register_in_eureka() if settings.eureka_enabled else False
    yield
    if registered:
        await eureka_client.stop_async()


app = FastAPI(
    title="report-service",
    description="Meteo App - weather reports and CSV/PDF exports (Report, ReportSchedule)",
    version="1.0.0",
    lifespan=lifespan,
)
register_exception_handlers(app)
app.include_router(report_router.router)
app.include_router(schedule_router.router)


@app.get("/health", tags=["monitoring"])
def health():
    return {"status": "UP"}


if __name__ == "__main__":
    import uvicorn

    uvicorn.run("app.main:app", host="0.0.0.0", port=settings.port)
